  /**
   * Get comprehensive gene profile
   */
  async getGeneProfile(geneId: string, cancerType?: string) {
    const [
      gene,
      depmap,
      gtex,
      constraint,
      structure,
      clinvar,
      drugs,
      trials,
      txscores,
    ] = await Promise.all([
      this.getGene(geneId),
      this.getDepMapData(geneId, cancerType),
      this.getGTExExpression(geneId),
      this.getGnomADConstraint(geneId),
      this.getAlphaFoldStructure(geneId),
      this.getClinVarVariants(geneId),
      this.getDrugInteractions(geneId),
      this.getClinicalTrials(geneId),
      cancerType
        ? this.getTxScore(geneId, cancerType).then((d) => (d ? [d] : []))
        : this.getTxScoresForGene(geneId),
    ]);

    return {
      gene,
      depmap,
      gtex,
      constraint,
      structure,
      clinvar: {
        all: clinvar,
        pathogenic: clinvar.filter((v) =>
          ['Pathogenic', 'Likely pathogenic'].includes(v.clinical_significance)
        ),
      },
      drugs: {
        all: drugs,
        approved: drugs.filter((d) => d.approval_status === 'approved'),
      },
      trials: {
        all: trials,
        advanced: trials.filter((t) =>
          ['Phase 2', 'Phase 3', 'Phase 4'].includes(t.phase || '')
        ),
        failed: trials.filter(
          (t) =>
            ['Terminated', 'Withdrawn'].includes(t.status) &&
            ['Phase 2', 'Phase 3'].includes(t.phase || '')
        ),
      },
      txscores,
    };
  }

