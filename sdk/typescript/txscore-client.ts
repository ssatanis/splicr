  /**
   * Compute and cache TxScore for a gene and cancer type
   */
  async computeAndCacheTxScore(
    geneId: string,
    cancerType: string,
    modelVersion: string = 'v1.0'
  ): Promise<TxScore> {
    const { data, error } = await this.supabase.rpc('compute_txscore' as any, {
      p_gene_id: geneId,
      p_cancer_type: cancerType,
      p_model_version: modelVersion,
    });

    if (error) throw error;
    return data as TxScore;
  }

  /**
   * Batch compute TxScores
   */
  async batchComputeTxScores(
    geneIds: string[],
    cancerTypes: string[],
    modelVersion: string = 'v1.0'
  ): Promise<TxScore[]> {
    const results: TxScore[] = [];

    for (const geneId of geneIds) {
      for (const cancerType of cancerTypes) {
        try {
          const score = await this.computeAndCacheTxScore(
            geneId,
            cancerType,
            modelVersion
          );
          results.push(score);
        } catch (err) {
          console.error(`Failed to compute TxScore for ${geneId} in ${cancerType}:`, err);
        }
      }
    }

    return results;
  }

  /**
   * Invalidate cache for a gene
   */
  async invalidateCache(geneId: string): Promise<void> {
    const { error } = await this.supabase
      .from('tx_txscore_cache')
      .delete()
      .eq('gene_id', geneId);

    if (error) throw error;
  }

  /**
   * Refresh stale cache entries
   */
  async refreshStaleCache(olderThanDays: number = 30): Promise<number> {
    const cutoffDate = new Date();
    cutoffDate.setDate(cutoffDate.getDate() - olderThanDays);

    const { data, error } = await this.supabase.rpc('refresh_stale_cache' as any, {
      p_cutoff_date: cutoffDate.toISOString(),
    });

    if (error) throw error;
    return (data as number) || 0;
  }

