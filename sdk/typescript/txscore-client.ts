  /**
   * Rank targets by composite criteria
   */
  async rankTargets(
    cancerType: string,
    weights: {
      efficacy?: number;
      safety?: number;
      druggability?: number;
      precedent?: number;
      stratification?: number;
    },
    limit: number = 100
  ): Promise<TxScore[]> {
    // Normalize weights to sum to 1
    const totalWeight = Object.values(weights).reduce((a, b) => a + b, 0);
    const normalizedWeights = Object.fromEntries(
      Object.entries(weights).map(([k, v]) => [k, v / totalWeight])
    );

    const { data, error } = await this.supabase.rpc('rank_targets_custom' as any, {
      p_cancer_type: cancerType,
      p_weights: normalizedWeights,
      p_limit: limit,
    });

    if (error) throw error;
    return (data || []) as TxScore[];
  }

