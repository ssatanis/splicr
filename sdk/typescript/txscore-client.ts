  /**
   * Get top targets for a cancer type
   */
  async getTopTargets(
    cancerType: string,
    filters?: TxScoreFilters,
    options?: RankingOptions
  ): Promise<TxScore[]> {
    let query = this.supabase
      .from('tx_txscore_cache')
      .select('*')
      .eq('cancer_type', cancerType);

    // Apply filters
    if (filters) {
      if (filters.min_tvs !== undefined) {
        query = query.gte('tvs', filters.min_tvs);
      }
      if (filters.min_efficacy !== undefined) {
        query = query.gte('efficacy_score', filters.min_efficacy);
      }
      if (filters.min_safety !== undefined) {
        query = query.gte('safety_score', filters.min_safety);
      }
      if (filters.min_druggability !== undefined) {
        query = query.gte('druggability_score', filters.min_druggability);
      }
      if (filters.recommended_modality !== undefined) {
        query = query.eq(
          'modality_recommendation->>recommended_modality',
          filters.recommended_modality
        );
      }
      if (filters.gene_ids && filters.gene_ids.length > 0) {
        query = query.in('gene_id', filters.gene_ids);
      }
    }

    // Apply ordering
    const orderBy = options?.order_by || 'tvs';
    const orderDirection = options?.order_direction || 'desc';
    query = query.order(orderBy, { ascending: orderDirection === 'asc' });

    // Apply pagination
    if (options?.limit !== undefined) {
      query = query.limit(options.limit);
    }
    if (options?.offset !== undefined) {
      query = query.range(
        options.offset,
        options.offset + (options.limit || 100) - 1
      );
    }

    const { data, error } = await query;

    if (error) throw error;
    return (data || []) as TxScore[];
  }

