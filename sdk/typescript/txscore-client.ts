/**
 * Normalize Chronos effect to [0, 1]
 * More negative = more essential
 */
export function normalizeChronos(chronosEffect: number): number {
  const clamped = Math.max(Math.min(chronosEffect, 0), -2.5);
  return (0 - clamped) / (0 - -2.5);
}

/**
 * Classify LOEUF constraint
 */
export function classifyLOEUF(loeuf: number): string {
  if (loeuf < 0.35) return 'highly_constrained';
  if (loeuf < 0.6) return 'constrained';
  if (loeuf < 1.0) return 'moderate';
  return 'unconstrained';
}

/**
 * Classify pLI
 */
export function classifyPLI(pli: number): string {
  if (pli > 0.9) return 'LoF_intolerant';
  if (pli > 0.5) return 'intermediate';
  return 'LoF_tolerant';
}

/**
 * Classify structure quality
 */
export function classifyStructureQuality(plddt: number): string {
  if (plddt > 90) return 'very_high';
  if (plddt > 70) return 'confident';
  if (plddt > 50) return 'low';
  return 'very_low';
}

/**
 * Classify TVS
 */
export function classifyTVS(tvs: number): string {
  if (tvs > 0.8) return 'exceptional';
  if (tvs > 0.7) return 'high';
  if (tvs > 0.5) return 'moderate';
  if (tvs > 0.3) return 'low';
  return 'very_low';
}

/**
 * Get color for TVS visualization
 */
export function getTVSColor(tvs: number): string {
  if (tvs > 0.8) return '#10b981'; // green
  if (tvs > 0.7) return '#84cc16'; // lime
  if (tvs > 0.5) return '#eab308'; // yellow
  if (tvs > 0.3) return '#f97316'; // orange
  return '#ef4444'; // red
}

/**
 * Format TPM for display
 */
export function formatTPM(tpm: number): string {
  if (tpm < 1) return tpm.toFixed(2);
  if (tpm < 10) return tpm.toFixed(1);
  return Math.round(tpm).toString();
}

/**
 * Format p-value
 */
export function formatPValue(p: number): string {
  if (p < 0.0001) return 'p < 0.0001';
  if (p < 0.001) return `p = ${p.toFixed(4)}`;
  if (p < 0.01) return `p = ${p.toFixed(3)}`;
  return `p = ${p.toFixed(2)}`;
}

