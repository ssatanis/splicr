/**
 * Renders the Supabase Auth email templates to `supabase/templates/`.
 *
 * The templates are built in TypeScript so the six messages share one theme and
 * one set of tests. Supabase wants finished HTML, pasted into Authentication,
 * Email Templates, or read from disk by the local stack. This script is the
 * bridge: it writes the HTML that gets pasted, plus a single-page preview with
 * the Go variables filled in so the set can be looked at in a browser.
 *
 *   node apps/web/scripts/build-auth-emails.mjs           write and report
 *   node apps/web/scripts/build-auth-emails.mjs --check    fail if out of date
 */
import fs from "node:fs";
import path from "node:path";

import { loadTs } from "../tests/helpers/load-ts.mjs";

const root = path.resolve(import.meta.dirname, "../../..");
const outDir = path.join(root, "supabase/templates");
const previewFile = path.join(outDir, "preview.html");

const { AUTH_EMAILS, renderPreview } = loadTs("lib/email/auth-templates.ts");

const check = process.argv.includes("--check");
const stale = [];

const write = (file, contents) => {
  const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  if (current === contents) return "unchanged";
  if (check) {
    stale.push(path.relative(root, file));
    return "stale";
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
  return current === null ? "created" : "updated";
};

for (const email of AUTH_EMAILS) {
  const state = write(path.join(outDir, email.file), `${email.html}\n`);
  console.log(`${state.padEnd(9)} supabase/templates/${email.file}  ${email.subject}`);
}

/* One page holding all six, so the theme can be reviewed as a set rather than
   one message at a time. It is a review aid, not something that is ever sent. */
const preview = `<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>SplicR authentication emails</title>
<style>
  body { margin:0; padding:40px 20px 80px; background:#F7F7F7; font:400 14px/1.5 -apple-system,BlinkMacSystemFont,'Segoe UI',Arial,sans-serif; color:#111; }
  .page { max-width:720px; margin:0 auto; }
  h1 { font-size:20px; font-weight:600; letter-spacing:-0.01em; margin:0 0 4px; }
  .lede { color:#757575; font-size:13px; margin:0 0 36px; }
  .item { margin:0 0 36px; }
  .meta { display:flex; justify-content:space-between; gap:16px; align-items:baseline; padding:0 0 8px; border-bottom:1px solid #E2E2E2; margin:0 0 0; }
  .dash { font-size:11px; font-weight:600; letter-spacing:0.12em; text-transform:uppercase; color:#24334B; }
  .subj { font-size:13px; color:#3D3D3D; }
  iframe { display:block; width:100%; height:760px; border:1px solid #E2E2E2; border-top:0; background:#fff; }
</style></head>
<body><div class="page">
<h1>SplicR authentication emails</h1>
<p class="lede">Rendered with placeholder values. Generated by apps/web/scripts/build-auth-emails.mjs, do not edit.</p>
${AUTH_EMAILS.map(
  (email) => `<div class="item">
  <div class="meta"><span class="dash">${email.dashboard}</span><span class="subj">${email.subject}</span></div>
  <iframe title="${email.dashboard}" srcdoc="${renderPreview(email).replace(/&/g, "&amp;").replace(/"/g, "&quot;")}"></iframe>
</div>`,
).join("\n")}
</div></body></html>
`;
console.log(`${write(previewFile, preview).padEnd(9)} supabase/templates/preview.html`);

if (check && stale.length) {
  console.error(`\nOut of date, run: npm run emails:auth\n${stale.map((file) => `  ${file}`).join("\n")}`);
  process.exit(1);
}
